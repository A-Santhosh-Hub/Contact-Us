  const browser = await chromium.launch({channel:'msedge',headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror',error => errors.push(error.message));
  await page.route('**/*',route => {
    if (route.request().resourceType() === 'document' && route.request().frame() !== page.mainFrame()) return route.fulfill({body:'<html><body>Preview transport test</body></html>',contentType:'text/html'});
    return route.continue();
  });
  fs.mkdirSync(path.join(__dirname,'../artifacts'),{recursive:true});
  await page.goto('http://127.0.0.1:4173',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(() => document.body.classList.contains('opening-active'));
  await page.screenshot({path:'artifacts/cinema-opening.png'});
  await page.locator('.skip-opening').click();
  assert.equal(await page.evaluate(() => document.body.classList.contains('opening-active')),false);
  console.log('PASS skippable opening');
  await page.evaluate(() => document.fonts.ready);
  for (const width of [1440,1024,768,390,320]) {
    await page.setViewportSize({width,height:900});
    await page.evaluate(() => scrollTo({top:0,behavior:'instant'}));
    await page.waitForTimeout(80);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),`Overflow ${width}`);
    const mark = await page.locator('.hero-wordmark').boundingBox();
    assert.ok(mark.x >= -1 && mark.x + mark.width <= width + 1,`Wordmark ${width}`);
    assert.equal(await page.locator('.glass-card').first().evaluate(el => getComputedStyle(el).backdropFilter),'none');
    await page.screenshot({path:`artifacts/cinema-${width}.png`});
    console.log(`PASS ${width}px layout, title and zero glass blur`);
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(() => scrollTo({top:450,behavior:'instant'}));
  await page.waitForTimeout(100);
  assert.ok(await page.locator('#home').evaluate(el => Number(el.style.getPropertyValue('--scene-zoom'))) > 1.15);
  await page.screenshot({path:'artifacts/cinema-zoom.png'});
  await page.evaluate(() => scrollTo({top:0,behavior:'instant'}));
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#home').evaluate(el => Number(el.style.getPropertyValue('--scene-zoom'))),1.02);
  await page.evaluate(() => scrollTo({top:1200,behavior:'instant'}));
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#main-header').evaluate(el => el.classList.contains('header-away')),true);
  await page.evaluate(() => scrollTo({top:1100,behavior:'instant'}));
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#main-header').evaluate(el => el.classList.contains('header-away')),false);
  console.log('PASS reversible scroll zoom and scroll-direction header');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(() => document.body.classList.contains('motion-paused'));
  assert.equal(await page.locator('.enter-world span').evaluate(el => getComputedStyle(el).animationName),'none');
  assert.equal(await page.locator('#home').evaluate(el => Math.round(el.getBoundingClientRect().height)),1000);
  console.log('PASS reduced motion disables opening, pinning and animation');
  await page.locator('.slide-next').click();
  await page.waitForFunction(() => document.querySelector('#project-reel').scrollLeft > 50);
  await page.waitForTimeout(100);
  assert.match(await page.locator('.slide-count').textContent(),/02/);
  await page.locator('.slide-prev').click();
  await page.waitForFunction(() => document.querySelector('#project-reel').scrollLeft < 5);
  await page.locator('[data-filter="tools"]').click();
  assert.equal(await page.locator('.project-card:not([hidden])').count(),3);
  await page.locator('[data-filter="games"]').click();
  assert.equal(await page.locator('.project-card:not([hidden])').count(),1);
  await page.waitForFunction(() => document.querySelector('.slide-next').disabled);
